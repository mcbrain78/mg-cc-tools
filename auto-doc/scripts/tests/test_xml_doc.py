def _round_trip(sections, audience="devops", diataxis="how-to",
                header=SAMPLE_HEADER, title="Operations Guide"):
    """Build -> serialize -> parse helper returning parsed doc dict."""
    tree = build_xml_doc(audience, diataxis, header, sections, title=title)
    with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as f:
        path = f.name
    try:
        serialize_xml_doc(tree, path)
        return parse_xml_doc(path)
    finally:
        os.unlink(path)


