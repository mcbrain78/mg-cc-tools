class TestAddSection:
    """add_section supports parent_path and sibling slug uniqueness."""

    def test_add_to_root_without_parent(self):
        """Without parent_path, section appends to root (backward compat)."""
        tree = build_xml_doc("devops", "how-to", "# Title", FLAT_SECTIONS)
        add_section(tree, "new-section", "## New Section\n\nNew body.")

        paths = get_section_paths(tree)
        assert "new-section" in paths

    def test_add_with_parent_path(self):
        """With parent_path, section appends as child of parent."""
        tree = build_xml_doc("devops", "how-to", "# Title", NESTED_SECTIONS_2)
        add_section(tree, "new-child", "### New Child\n\nChild body.",
                    parent_path="monitoring-alerting")

        paths = get_section_paths(tree)
        assert "monitoring-alerting/new-child" in paths

    def test_missing_parent_raises(self):
        """Nonexistent parent_path raises ValueError."""
        tree = build_xml_doc("devops", "how-to", "# Title", FLAT_SECTIONS)
        with pytest.raises(ValueError, match="nonexistent"):
            add_section(tree, "child", "body", parent_path="nonexistent")

    def test_duplicate_sibling_slug_raises(self):
        """Adding a section with a slug that already exists as a sibling raises."""
        tree = build_xml_doc("devops", "how-to", "# Title", NESTED_SECTIONS_2)
        with pytest.raises(ValueError, match="etl-run-logging"):
            add_section(tree, "etl-run-logging", "duplicate body",
                        parent_path="monitoring-alerting")

    def test_same_slug_different_parents_ok(self):
        """Same slug under different parents is allowed (sibling uniqueness)."""
