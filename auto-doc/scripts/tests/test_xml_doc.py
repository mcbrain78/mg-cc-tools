class TestBuildAndParse:
    """build_xml_doc + parse_xml_doc round-trip for flat and nested."""

    def test_round_trip_flat_structure(self):
        """Flat sections (no children key) still work -- backward compat."""
        doc = _round_trip(FLAT_SECTIONS)

        assert doc["audience"] == "devops"
        assert doc["diataxis"] == "how-to"
        assert doc["meta"]["title"] == "Operations Guide"
        assert doc["meta"]["header"] == SAMPLE_HEADER
        assert len(doc["sections"]) == 2
        assert doc["sections"][0]["slug"] == "monitoring-alerting"
        assert doc["sections"][1]["slug"] == "deployment"
        assert "ETL run log" in doc["sections"][0]["body"]
        assert "CI/CD" in doc["sections"][1]["body"]
        # Flat sections have empty children
        assert doc["sections"][0]["children"] == []
        assert doc["sections"][1]["children"] == []

    def test_round_trip_nested_2_levels(self):
        """2-level nesting preserves children structure."""
        doc = _round_trip(NESTED_SECTIONS_2)

        assert len(doc["sections"]) == 2
        parent = doc["sections"][0]
        assert parent["slug"] == "monitoring-alerting"
        assert "Intro to monitoring" in parent["body"]
        assert len(parent["children"]) == 2

        child1 = parent["children"][0]
        assert child1["slug"] == "etl-run-logging"
        assert "Logs all pipeline runs" in child1["body"]
        assert child1["children"] == []

        child2 = parent["children"][1]
        assert child2["slug"] == "alert-routing"
        assert "Routes alerts" in child2["body"]
        assert child2["children"] == []

        # Second top-level is a leaf
        assert doc["sections"][1]["slug"] == "deployment"
        assert doc["sections"][1]["children"] == []

    def test_round_trip_nested_3_levels(self):
        """3-level nesting preserves grandchild structure."""
        doc = _round_trip(NESTED_SECTIONS_3)

        parent = doc["sections"][0]
        assert parent["slug"] == "monitoring-alerting"

        child = parent["children"][0]
        assert child["slug"] == "etl-run-logging"

        grandchild = child["children"][0]
        assert grandchild["slug"] == "artifact-format"
        assert "JSON artifact" in grandchild["body"]
        assert grandchild["children"] == []

    def test_body_isolation(self):
        """Each section body contains only its own prose, not child content."""
        doc = _round_trip(NESTED_SECTIONS_2)

        parent = doc["sections"][0]
        # Parent body has intro text but NOT child content
        assert "Intro to monitoring" in parent["body"]
        assert "Logs all pipeline runs" not in parent["body"]
        assert "Routes alerts" not in parent["body"]

    def test_children_default_empty_when_absent(self):
        """Sections without 'children' key default to empty list."""
        sections_no_children = [
            {"slug": "overview", "body": "## Overview\n\nText."},
        ]
        doc = _round_trip(sections_no_children)
        assert doc["sections"][0]["children"] == []

    def test_title_extracted_from_header(self):
        """Title is extracted from header if not explicitly provided."""
        tree = build_xml_doc("devops", "how-to", SAMPLE_HEADER, [])
        with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as f:
            path = f.name
        try:
            serialize_xml_doc(tree, path)
            doc = parse_xml_doc(path)
            assert doc["meta"]["title"] == "Operations Guide"
        finally:
            os.unlink(path)

    def test_empty_sections(self):
        """Document with no sections is valid."""
        doc = _round_trip([], audience="end-users", diataxis="tutorial",
                          header="# Guide", title="Guide")
        assert doc["sections"] == []
        assert doc["audience"] == "end-users"

    def test_empty_refs(self):
        """Sections start with empty refs at all levels."""
        doc = _round_trip(NESTED_SECTIONS_2)
        for section in doc["sections"]:
            assert section["refs"] == []
            for child in section["children"]:
                assert child["refs"] == []


