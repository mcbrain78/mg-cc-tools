class TestWalkSections:
    """walk_sections yields (path, section_dict) in depth-first order."""

    def test_empty_list(self):
        """walk_sections on empty list yields nothing."""
        result = list(walk_sections([]))
        assert result == []

    def test_flat_sections(self):
        """Flat sections yield bare slugs as paths."""
        doc = _round_trip(FLAT_SECTIONS)
        result = list(walk_sections(doc["sections"]))
        assert len(result) == 2
        assert result[0][0] == "monitoring-alerting"
        assert result[0][1]["slug"] == "monitoring-alerting"
        assert result[1][0] == "deployment"
        assert result[1][1]["slug"] == "deployment"

    def test_nested_sections_depth_first(self):
        """Nested sections yield depth-first paths with slash separators."""
        doc = _round_trip(NESTED_SECTIONS_2)
        result = list(walk_sections(doc["sections"]))

        paths = [p for p, _ in result]
        assert paths == [
            "monitoring-alerting",
            "monitoring-alerting/etl-run-logging",
            "monitoring-alerting/alert-routing",
            "deployment",
        ]

    def test_3_level_paths(self):
        """3-level nesting produces grandchild paths."""
        doc = _round_trip(NESTED_SECTIONS_3)
        result = list(walk_sections(doc["sections"]))

        paths = [p for p, _ in result]
        assert paths == [
            "monitoring-alerting",
            "monitoring-alerting/etl-run-logging",
            "monitoring-alerting/etl-run-logging/artifact-format",
        ]

    def test_yields_section_dicts(self):
        """Each yielded item is a section dict with slug, body, refs, children."""
        doc = _round_trip(NESTED_SECTIONS_2)
        for path, section in walk_sections(doc["sections"]):
            assert "slug" in section
            assert "body" in section
            assert "refs" in section
            assert "children" in section


