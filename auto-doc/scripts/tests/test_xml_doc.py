"""Tests for lib/xml_doc.py -- XML document model.

Covers build, parse, serialize, and mutation helpers. Verifies round-trip
fidelity: build → serialize → parse yields identical structure.
"""

import os
import sys
import tempfile

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from lib.xml_doc import (
    build_xml_doc,
    get_section_slugs,
    parse_xml_doc,
    serialize_xml_doc,
    update_section_body,
    update_section_refs,
)

SAMPLE_HEADER = """<!-- This file is auto-generated by /mg:auto-doc -->
<!-- DIATAXIS: how-to -->
<!-- AUDIENCE: devops -->

# Operations Guide"""

SAMPLE_SECTIONS = [
    {
        "slug": "monitoring-alerting",
        "body": "<!-- section: monitoring-alerting -->\n## Monitoring & Alerting\n\nThe ETL run log tracks all pipeline executions.",
    },
    {
        "slug": "deployment",
        "body": "<!-- section: deployment -->\n## Deployment\n\nDeploy via CI/CD pipeline.",
    },
]


class TestBuildAndParse:
    """build_xml_doc + parse_xml_doc round-trip."""

    def test_round_trip_structure(self):
        """Build → serialize → parse preserves audience, diataxis, header, sections."""
        tree = build_xml_doc("devops", "how-to", SAMPLE_HEADER, SAMPLE_SECTIONS,
                             title="Operations Guide")

        with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as f:
            path = f.name
        try:
            serialize_xml_doc(tree, path)
            doc = parse_xml_doc(path)

            assert doc["audience"] == "devops"
            assert doc["diataxis"] == "how-to"
            assert doc["meta"]["title"] == "Operations Guide"
            assert doc["meta"]["header"] == SAMPLE_HEADER
            assert len(doc["sections"]) == 2
            assert doc["sections"][0]["slug"] == "monitoring-alerting"
            assert doc["sections"][1]["slug"] == "deployment"
            assert "ETL run log" in doc["sections"][0]["body"]
            assert "CI/CD" in doc["sections"][1]["body"]
        finally:
            os.unlink(path)

    def test_title_extracted_from_header(self):
        """Title is extracted from header if not explicitly provided."""
        tree = build_xml_doc("devops", "how-to", SAMPLE_HEADER, [])
        with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as f:
            path = f.name
        try:
            serialize_xml_doc(tree, path)
            doc = parse_xml_doc(path)
            assert doc["meta"]["title"] == "Operations Guide"
        finally:
            os.unlink(path)

    def test_empty_sections(self):
        """Document with no sections is valid."""
        tree = build_xml_doc("end-users", "tutorial", "# Guide", [])
        with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as f:
            path = f.name
        try:
            serialize_xml_doc(tree, path)
            doc = parse_xml_doc(path)
            assert doc["sections"] == []
            assert doc["audience"] == "end-users"
        finally:
            os.unlink(path)

    def test_empty_refs(self):
        """Sections start with empty refs."""
        tree = build_xml_doc("devops", "how-to", SAMPLE_HEADER, SAMPLE_SECTIONS)
        with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as f:
            path = f.name
        try:
            serialize_xml_doc(tree, path)
            doc = parse_xml_doc(path)
            for section in doc["sections"]:
                assert section["refs"] == []
        finally:
            os.unlink(path)


class TestGetSectionSlugs:
    """get_section_slugs returns ordered slugs."""

    def test_returns_slugs_in_order(self):
        tree = build_xml_doc("devops", "how-to", "# Title", SAMPLE_SECTIONS)
